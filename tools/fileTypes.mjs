// The file types GRSMD opens (spec 5.4, INV-102, owner rulings AQ1, AQ5,
// AQ9, AQ12). One source, spec/data/file-types.json, one row per entry in
// the order written; one step from it to every output, never from an output:
// (1) the table in spec 5.4 between BEGIN_MARKER and END_MARKER, and (2)
// src/js/fileTypes.js, the constant the app reads (config.js). No fixture
// for the tests: they read src/js/fileTypes.js, which (2) keeps equal to the
// source.
//
//   node tools/fileTypes.mjs          write the outputs
//   node tools/fileTypes.mjs --check  exit 1 when an output differs, byte for byte
//
// The unit test AT-GEN (src/__tests__/fileTypes.test.js) runs the same check
// through checkOutputs. No dependencies, no network.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE = "spec/data/file-types.json";
export const CODE_OUTPUT = "src/js/fileTypes.js";
export const SPEC_OUTPUT = "spec/grsmd_gen2_spec_ja.md";
export const BEGIN_MARKER = "<!-- file-types:begin (generated by tools/fileTypes.mjs from spec/data/file-types.json; do not edit by hand) -->";
export const END_MARKER = "<!-- file-types:end -->";
// The spec is Japanese; its words are written as escapes to keep this file
// ASCII. The heading reads: "A generated table. Do not edit by hand (made
// from spec/data/file-types.json by tools/fileTypes.mjs)".
export const SPEC_HEADING =
  "\u751f\u6210\u3057\u305f\u8868\u3002\u624b\u3067\u76f4\u3055\u306a\u3044 (spec/data/file-types.json \u304b\u3089 tools/fileTypes.mjs \u304c\u4f5c\u308b)";
// The table's words: the columns ID, kind, match, opens in, highlight.js;
// the kinds extension and name; the views Markdown preview and code view;
// and "no colors".
const JA = {
  header: "| ID | \u7a2e\u985e | \u4e00\u81f4 | \u958b\u304d\u65b9 | highlight.js |",
  extension: "\u62e1\u5f35\u5b50",
  name: "\u540d\u524d",
  markdown: "Markdown \u30d7\u30ec\u30d3\u30e5\u30fc",
  code: "\u30b3\u30fc\u30c9\u30d3\u30e5\u30fc",
  noColors: "\u8272\u306a\u3057",
};
/** How a row opens: the Markdown preview or the code view. */
export const OPEN_KINDS = ["markdown", "code"];
export const MIN_ROWS = 90;

const FIELDS = ["id", "match", "open", "hljs"];
const ID = /^FT-[1-9]\d*$/;
// An extension: a dot, then lower case letters and digits (the app lower-cases
// the extension before the lookup, so an upper case one could never match).
const EXTENSION = /^\.[a-z0-9]+$/;
// A whole file name without a dot (a dotted name is looked up by its extension first).
const NAME = /^[A-Za-z0-9_-]+$/;
const HLJS = /^[a-z0-9]+$/;

/**
 * Everything wrong with the rows; empty when they can be used.
 * @param {unknown} rows - the parsed source
 * @returns {string[]}
 * @purity pure
 */
export function problemsOf(rows) {
  if (!Array.isArray(rows)) return ["the source is not an array"];
  const problems = [];
  const ids = new Set();
  const matches = new Set();
  rows.forEach((row, i) => {
    const at = `row ${i + 1}`;
    if (row === null || typeof row !== "object" || Array.isArray(row)) {
      problems.push(`${at}: not an object`);
      return;
    }
    for (const field of FIELDS) if (!(field in row)) problems.push(`${at}: missing field "${field}"`);
    for (const field of Object.keys(row)) if (!FIELDS.includes(field)) problems.push(`${at}: unknown field "${field}"`);
    if ("id" in row) {
      if (typeof row.id !== "string" || !ID.test(row.id)) problems.push(`${at}: bad id ${JSON.stringify(row.id)}`);
      else if (ids.has(row.id)) problems.push(`${at}: duplicate id ${row.id}`);
      else ids.add(row.id);
    }
    if ("match" in row) {
      const m = row.match;
      if (typeof m !== "string" || !(EXTENSION.test(m) || NAME.test(m))) problems.push(`${at}: bad match ${JSON.stringify(m)}`);
      else if (matches.has(m)) problems.push(`${at}: duplicate match ${m}`);
      else matches.add(m);
    }
    if ("open" in row && !OPEN_KINDS.includes(row.open)) problems.push(`${at}: unknown open ${JSON.stringify(row.open)}`);
    if ("hljs" in row && row.hljs !== null && !(typeof row.hljs === "string" && HLJS.test(row.hljs))) {
      problems.push(`${at}: bad hljs ${JSON.stringify(row.hljs)}`);
    }
  });
  if (rows.length < MIN_ROWS) problems.push(`${rows.length} rows: at least ${MIN_ROWS} expected`);
  return problems;
}

/**
 * The rows, checked; throws with every problem found.
 * @param {string} sourceText - the source file's text
 * @returns {{id: string, match: string, open: string, hljs: string|null}[]}
 * @purity pure
 */
export function rowsOf(sourceText) {
  const rows = JSON.parse(sourceText);
  const problems = problemsOf(rows);
  if (problems.length > 0) throw new Error(`${SOURCE}:\n  ${problems.join("\n  ")}`);
  return rows;
}

/**
 * src/js/fileTypes.js for the rows.
 * @param {{id: string, match: string, open: string, hljs: string|null}[]} rows
 * @returns {string}
 * @purity pure
 */
export function codeModuleOf(rows) {
  const lines = rows.map(
    (r) => `  { id: ${JSON.stringify(r.id)}, match: ${JSON.stringify(r.match)}, open: ${JSON.stringify(r.open)}, hljs: ${JSON.stringify(r.hljs)} },`,
  );
  return [
    "// Generated. Do not edit.",
    `// From ${SOURCE} by tools/fileTypes.mjs (spec 5.4, INV-102).`,
    "//",
    "// The file types GRSMD opens (INV-18): match is an extension (lower case,",
    "// with the dot) or a whole file name; open is \"markdown\" (the Markdown",
    "// preview) or \"code\" (the code view); hljs is the highlight.js language",
    "// of the code view, or null (no colors).",
    "",
    "/** @type {ReadonlyArray<Readonly<{id: string, match: string, open: \"markdown\"|\"code\", hljs: string|null}>>} */",
    "export const FILE_TYPES = Object.freeze(",
    "  [",
    ...lines.map((l) => `  ${l}`),
    "  ].map((row) => Object.freeze(row)),",
    ");",
    "",
  ].join("\n");
}

/**
 * The lines between the two markers of spec 5.4 (the markers not included):
 * the heading, the table and a blank line.
 * @param {{id: string, match: string, open: string, hljs: string|null}[]} rows
 * @returns {string}
 * @purity pure
 */
export function specTableOf(rows) {
  const kind = (m) => (m.startsWith(".") ? JA.extension : JA.name);
  const hljs = (h) => (h === null ? JA.noColors : `\`${h}\``);
  return [
    SPEC_HEADING,
    "",
    JA.header,
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.id} | ${kind(r.match)} | \`${r.match}\` | ${JA[r.open]} | ${hljs(r.hljs)} |`),
    "", // a blank line ends the table before the end marker
  ].join("\n");
}

/**
 * The spec with the table between its markers replaced. Throws when a
 * marker is missing or not alone (each on its own line, once).
 * @param {string} specText
 * @param {string} table - specTableOf
 * @returns {string}
 * @purity pure
 */
export function specWithTable(specText, table) {
  const eol = specText.includes("\r\n") ? "\r\n" : "\n";
  const lines = specText.split(eol);
  const begin = lines.flatMap((l, i) => (l === BEGIN_MARKER ? [i] : []));
  const end = lines.flatMap((l, i) => (l === END_MARKER ? [i] : []));
  if (begin.length !== 1 || end.length !== 1 || end[0] < begin[0]) {
    throw new Error(`the markers must be there once each, in order, on their own lines:\n  ${BEGIN_MARKER}\n  ${END_MARKER}`);
  }
  return [...lines.slice(0, begin[0] + 1), ...table.split("\n"), ...lines.slice(end[0])].join(eol);
}

/**
 * An LF text with the line endings of the file it replaces: a checkout with
 * core.autocrlf has CRLF files, and the check compares bytes.
 * @param {string} text - LF line endings
 * @param {string|null} current - the file now, or null
 * @returns {string}
 * @purity pure
 */
export function withEolOf(text, current) {
  return current !== null && current.includes("\r\n") ? text.replace(/\n/g, "\r\n") : text;
}

/**
 * Every output: its path (from the root), what it holds now (null: no
 * file), and what it must hold, or the problem that keeps it from being made
 * (the spec without its markers). One output's problem does not stop the other.
 * @param {string} root - the repository folder
 * @returns {{path: string, actual: string|null, expected: string|null, problem: string|null}[]}
 * @purity non-pure
 */
export function outputsOf(root) {
  const read = (path) => {
    try {
      return readFileSync(resolve(root, path), "utf8");
    } catch {
      return null;
    }
  };
  const rows = rowsOf(readFileSync(resolve(root, SOURCE), "utf8"));
  const made = (path, make) => {
    const actual = read(path);
    try {
      return { path, actual, expected: make(actual), problem: null };
    } catch (error) {
      return { path, actual, expected: null, problem: error.message };
    }
  };
  return [
    made(CODE_OUTPUT, (actual) => withEolOf(codeModuleOf(rows), actual)),
    made(SPEC_OUTPUT, (actual) => specWithTable(actual ?? "", specTableOf(rows))),
  ];
}

/**
 * The outputs that differ from what the source makes (byte for byte), or
 * that cannot be made.
 * @param {string} root
 * @returns {{path: string, problem: string}[]}
 * @purity non-pure
 */
export function checkOutputs(root) {
  return outputsOf(root)
    .filter((o) => o.problem !== null || o.actual !== o.expected)
    .map((o) => ({ path: o.path, problem: o.problem ?? `differs from ${SOURCE} (run node tools/fileTypes.mjs)` }));
}

/**
 * Write the outputs that differ. Throws, writing nothing, when a wanted
 * output cannot be made.
 * @param {string} root
 * @param {(path: string) => boolean} [wanted] - which outputs to write (all when not given)
 * @returns {string[]} the paths written
 * @purity non-pure
 */
export function writeOutputs(root, wanted = () => true) {
  const outputs = outputsOf(root).filter((o) => wanted(o.path));
  const problems = outputs.filter((o) => o.problem !== null);
  if (problems.length > 0) throw new Error(problems.map((o) => o.problem).join("\n"));
  const written = [];
  for (const o of outputs) {
    if (o.actual === o.expected) continue;
    writeFileSync(resolve(root, o.path), o.expected);
    written.push(o.path);
  }
  return written;
}

/**
 * The command line.
 * @purity non-pure
 */
function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  if (process.argv.includes("--check")) {
    const failed = checkOutputs(root);
    for (const f of failed) console.error(`${f.path}: ${f.problem}`);
    process.exit(failed.length > 0 ? 1 : 0);
  }
  for (const path of writeOutputs(root)) console.log(`written: ${path}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
